CREATE TABLE users (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  email VARCHAR(255) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('student', 'coordinator') NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  last_login_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email),
  KEY idx_users_role_active (role, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE coordinators (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  college_id INT UNSIGNED NOT NULL,
  employee_number VARCHAR(64) NULL,
  first_name VARCHAR(100) NOT NULL,
  middle_name VARCHAR(100) NULL,
  last_name VARCHAR(100) NOT NULL,
  position_title VARCHAR(120) NULL,
  contact_number VARCHAR(32) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_coordinators_user_id (user_id),
  UNIQUE KEY uq_coordinators_employee_number (employee_number),
  KEY idx_coordinators_college_id (college_id),
  CONSTRAINT fk_coordinators_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_coordinators_college_id FOREIGN KEY (college_id) REFERENCES colleges (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE students (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id INT UNSIGNED NOT NULL,
  college_id INT UNSIGNED NOT NULL,
  program_id INT UNSIGNED NOT NULL,
  academic_term_id INT UNSIGNED NOT NULL,
  student_number VARCHAR(32) NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  middle_name VARCHAR(100) NULL,
  last_name VARCHAR(100) NOT NULL,
  year_level TINYINT UNSIGNED NOT NULL DEFAULT 4,
  section VARCHAR(64) NOT NULL,
  contact_number VARCHAR(32) NULL,
  address TEXT NULL,
  eligibility_status ENUM('eligible', 'for_review', 'incomplete', 'not_eligible') NOT NULL DEFAULT 'incomplete',
  eligibility_updated_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_students_user_id (user_id),
  UNIQUE KEY uq_students_student_number (student_number),
  KEY idx_students_college_id (college_id),
  KEY idx_students_program_id (program_id),
  KEY idx_students_term_id (academic_term_id),
  KEY idx_students_eligibility (eligibility_status),
  CONSTRAINT fk_students_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT fk_students_college_id FOREIGN KEY (college_id) REFERENCES colleges (id) ON DELETE RESTRICT,
  CONSTRAINT fk_students_program_id FOREIGN KEY (program_id) REFERENCES programs (id) ON DELETE RESTRICT,
  CONSTRAINT fk_students_academic_term_id FOREIGN KEY (academic_term_id) REFERENCES academic_terms (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
