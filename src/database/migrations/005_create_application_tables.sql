CREATE TABLE applications (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  application_code VARCHAR(32) NULL,
  student_id INT UNSIGNED NOT NULL,
  company_id INT UNSIGNED NOT NULL,
  academic_term_id INT UNSIGNED NOT NULL,
  status ENUM('submitted', 'under_review', 'shortlisted', 'accepted', 'rejected', 'withdrawn') NOT NULL DEFAULT 'submitted',
  student_notes TEXT NULL,
  coordinator_remarks TEXT NULL,
  reviewed_by_user_id INT UNSIGNED NULL,
  reviewed_at TIMESTAMP NULL DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_applications_code (application_code),
  KEY idx_applications_student_id (student_id),
  KEY idx_applications_company_id (company_id),
  KEY idx_applications_term_status (academic_term_id, status),
  CONSTRAINT fk_applications_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
  CONSTRAINT fk_applications_company_id FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
  CONSTRAINT fk_applications_academic_term_id FOREIGN KEY (academic_term_id) REFERENCES academic_terms (id) ON DELETE RESTRICT,
  CONSTRAINT fk_applications_reviewed_by FOREIGN KEY (reviewed_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE placements (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  student_id INT UNSIGNED NOT NULL,
  company_id INT UNSIGNED NOT NULL,
  application_id INT UNSIGNED NULL,
  academic_term_id INT UNSIGNED NOT NULL,
  status ENUM('confirmed', 'deployed', 'completed', 'cancelled') NOT NULL DEFAULT 'confirmed',
  start_date DATE NULL,
  end_date DATE NULL,
  hours_rendered DECIMAL(6, 2) NOT NULL DEFAULT 0.00,
  supervisor_name VARCHAR(150) NULL,
  supervisor_email VARCHAR(255) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_placements_student_term (student_id, academic_term_id),
  KEY idx_placements_company_id (company_id),
  KEY idx_placements_status (status),
  CONSTRAINT fk_placements_student_id FOREIGN KEY (student_id) REFERENCES students (id) ON DELETE CASCADE,
  CONSTRAINT fk_placements_company_id FOREIGN KEY (company_id) REFERENCES companies (id) ON DELETE RESTRICT,
  CONSTRAINT fk_placements_application_id FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE SET NULL,
  CONSTRAINT fk_placements_academic_term_id FOREIGN KEY (academic_term_id) REFERENCES academic_terms (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
