CREATE TABLE companies (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  partner_code VARCHAR(32) NULL,
  name VARCHAR(255) NOT NULL,
  industry VARCHAR(120) NOT NULL,
  partnership_label VARCHAR(120) NULL,
  description TEXT NULL,
  focus_area VARCHAR(255) NULL,
  skills_json JSON NULL,
  address TEXT NOT NULL,
  city VARCHAR(120) NOT NULL,
  province VARCHAR(120) NOT NULL,
  contact_person VARCHAR(150) NOT NULL,
  contact_email VARCHAR(255) NOT NULL,
  contact_phone VARCHAR(32) NULL,
  website_url VARCHAR(255) NULL,
  logo_path VARCHAR(255) NULL,
  slot_quota INT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  created_by_user_id INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_companies_partner_code (partner_code),
  KEY idx_companies_status (status),
  KEY idx_companies_industry (industry),
  CONSTRAINT fk_companies_created_by FOREIGN KEY (created_by_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
